// =====================================================================
// uart_out.h —— 按"整行"发货的串口输出（所有固件共用一份）
//
// ★ 2026-11-02 的结论：平台的串口工具**每次只取 24 字节**。
//
//   实测日志（22:55:06 起，CoreMark 稳态段）连续十余条 RX 的负载**恰好 24 字符**：
//       reMark Size    : 666\nTot          24
//       al ticks      : 1155785723         25
//       \nTotal time (secs): 11.           24
//       415\nIterations/Sec   : 5          24
//       : -march=rv32i_zmmul -mn           24
//   而间隔在 480~510 ms 之间抖动，偶发 127 ms / 860 ms。
//   ⇒ 机制是"每 ~500 ms 读 24 字节"，不是"读走全部"。
//
//   20 ms/字节（50 B/s）× 500 ms = 25 字节 ≈ 24 字节，正好卡在它的读取上限，
//   所以缓冲区长期是**满**的 —— 读指针落在哪一行中间完全是随机的，
//   这就是"每句都被劈成两半、断在词中间"的根因。**调慢并不能解决**：
//   调慢只是让每 500 ms 少产几个字节，切割点照样在句中。
//
//   正确的做法（本文件实现）：
//     ① **一行不超过 24 字节**（22 个可见字符 + CRLF）—— 超过就按空格折行；
//     ② 段内**全速**发完（22 字节约 2 ms，比一次轮询短两个数量级）；
//     ③ 段后**静默 600 ms**（> 轮询周期 500 ms），保证中间至少有一次"空读"，
//        缓冲区被排空，下一次轮询拿到的一定是下一整段。
//   ⇒ 每条 RX = 一整行，且行尾一定落在词边界上。
//
//   吞吐 ≈ 22 字节 / 0.62 s ≈ 35 B/s（原来是 50 B/s 但句子全断）。
//   档位运行时可变：菜单按 3 循环，不必重出码流。
//
// 为什么 busy 轮询要有上限
//   busy 位万一读回恒为 1（外设读通道/桥出问题），老代码会在这里无限等，
//   现象是"串口一个字都没有"且 LED 上完全看不出来。宁可丢字节也不卡死。
// =====================================================================
#ifndef UART_OUT_H
#define UART_OUT_H

#include <stdint.h>

/* 一段最多多少**可见字符**（不含 CRLF）。22 + 2 = 24 = 平台一次读取的上限。
   改大就会重新开始切句子，别动。 */
#define UART_SEG_MAX   22u

/* 段与段之间静默多久。必须 > 平台轮询周期（实测 ~500 ms，偶发 860 ms）。 */
#define UART_GAP_DEFAULT_MS   600u

/* 段内每字节的额外停顿（0 = 全速 115200）。默认 0：
   22 字节 1.9 ms 冲完，被轮询撞进中间的概率只有 1.9/600 ≈ 0.3%。
   只有怀疑"接收端按字节丢"时才靠菜单 3 切到 1 ms。 */
#define UART_INTRA_DEFAULT_MS 0u

/* 一次 busy 轮询的上限（约 3~4 ms，远大于一个字节的 0.087 ms） */
#define UART_POLL_MAX   30000u

/* 当前节奏：段间静默 / 段内每字节（毫秒）。菜单可改，gate_board 会打印。 */
extern uint32_t g_uart_gap_ms;
extern uint32_t g_uart_intra_ms;

/* 运行时改节奏 */
void uart_set_pace(uint32_t gap_ms, uint32_t intra_ms);

/* 发一个字符。'\n' 触发"发一段"（自动补 '\r'）；'\r' 被忽略。 */
void uart_putc(char c);

/* 发一个字符串 */
void uart_puts(const char *s);

/* 把还没发出去的半行强行发掉（提示符 "> " 这种不带换行的要用）。 */
void uart_flush(void);

/* 毫秒延时：优先用 SoC 周期计数器 0x3000_0000（101.25 MHz），
   读不到时退回空转。任何时候都不会死等。 */
void uart_delay_ms(uint32_t ms);

#endif /* UART_OUT_H */
